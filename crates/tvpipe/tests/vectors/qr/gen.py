"""Generates the known-answer QR codes for src/util/qr.rs.

    uv venv -p 3.12 /tmp/qrvenv
    VIRTUAL_ENV=/tmp/qrvenv uv pip install qrcodegen==1.8.0 segno==1.6.6 zxing-cpp numpy
    /tmp/qrvenv/bin/python tests/vectors/qr/gen.py > tests/vectors/qr/symbols.txt

Symbols: Nayuki's qrcodegen (byte mode, the input as bytes, no level
boost, the smallest version, automatic mask); `penalties` are its scores
of masks 0..7. Each symbol is checked to decode with zxing-cpp. Block
structure: segno's tables (an independent source).
"""

import numpy
import qrcodegen
import segno
import zxingcpp
from qrcodegen import QrCode, QrSegment

CASES = [
    ("v1", b"tvpipe", QrCode.Ecc.MEDIUM),
    ("short", b"https://example.com/", QrCode.Ecc.MEDIUM),
    ("player-local", b"http://127.0.0.1:8765/?t=Zm9vYmFyYmF6cXV4", QrCode.Ecc.MEDIUM),
    ("player-cloudflare",
     b"https://graduate-variables-lifetime-ridge.trycloudflare.com/"
     b"?t=4e8a1c2f9b7d3e6a0f5c8b1d2e9a7c4f&delay=300", QrCode.Ecc.MEDIUM),
    ("share-opentunnel",
     b"https://share.k3j9x2m7q8w4.opentunnel.xyz/?t=8f3a2b1c9d0e7f6a5b4c3d2e1f0a9b8c"
     b"7d6e5f4a3b2c1d0e9f8a7b6c5d4e3f2a1b0c", QrCode.Ecc.MEDIUM),
    ("v10-count16", b"https://example.com/" + b"a" * 190, QrCode.Ecc.MEDIUM),
    ("utf8", "https://example.com/grüße?q=日本".encode(), QrCode.Ecc.MEDIUM),
    ("level-l", b"https://example.com/" + b"x" * 380, QrCode.Ecc.LOW),
]


def make(data, ecl, mask=-1):
    seg = QrSegment.make_bytes(data)
    return QrCode.encode_segments([seg], ecl, mask=mask, boostecl=False)


def decodes(qr):
    border, scale = 4, 4
    n = qr.get_size()
    img = numpy.full(((n + 2 * border) * scale,) * 2, 255, numpy.uint8)
    for y in range(n):
        for x in range(n):
            if qr.get_module(x, y):
                ys, xs = (y + border) * scale, (x + border) * scale
                img[ys:ys + scale, xs:xs + scale] = 0
    found = zxingcpp.read_barcodes(img)
    return [r.bytes for r in found]


print("# Known-answer QR codes for src/util/qr.rs.")
print("# Generated by tests/vectors/qr/gen.py: symbols from qrcodegen 1.8.0 (Nayuki),")
print(f"# block structure from segno {segno.__version__}; every symbol decodes with zxing-cpp.")
print("# data: hex; matrix: rows top to bottom, 1 dark.")
for name, data, ecl in CASES:
    qr = make(data, ecl)
    assert decodes(qr) == [data], name
    penalties = [make(data, ecl, m)._get_penalty_score() for m in range(8)]
    assert min(penalties) == penalties[qr.get_mask()]
    print()
    print(f"name = {name}")
    print(f"data = {data.hex()}")
    print(f"error = {'M' if ecl == QrCode.Ecc.MEDIUM else 'L'}")
    print(f"version = {qr.get_version()}")
    print(f"mask = {qr.get_mask()}")
    print("penalties = " + " ".join(str(p) for p in penalties))
    print("matrix =")
    n = qr.get_size()
    for y in range(n):
        print("  " + "".join("1" if qr.get_module(x, y) else "0" for x in range(n)))

# Block structure of every version at L and M: blocks, ECC per block,
# data codewords (segno.consts.ECC).
print()
print("name = blocks")
for label, level in (("l", segno.consts.ERROR_LEVEL_L), ("m", segno.consts.ERROR_LEVEL_M)):
    rows = []
    for version in range(1, 41):
        ecs = segno.consts.ECC[version][level]
        blocks = sum(e.num_blocks for e in ecs)
        ecc = {e.num_total - e.num_data for e in ecs}
        assert len(ecc) == 1
        data = sum(e.num_blocks * e.num_data for e in ecs)
        rows.append(f"{blocks}/{ecc.pop()}/{data}")
    print(f"{label} = " + " ".join(rows))
