    #[test]
    fn quant_dequant_consistent() {
        // MF · V ≈ 2^17 · {1, 0.64, 0.8}: quantise then rescale is the
        // identity up to the transform's norms (Richardson, ch. 7).
        for m in 0..6 {
            for (c, k) in [1.0, 0.64, 0.8].iter().enumerate() {
                let r = (QUANT_MF[m][c] * DEQUANT_V[m][c]) as f64 / (131072.0 * k);
                assert!((r - 1.0).abs() < 0.01, "{m} {c} {r}");
            }
        }
    }
