#!/usr/bin/env bash
# Regenerates tests/fixtures/media/*.mkv and tests/vectors/mkv/*.txt.
#
# The vectors hold what `ffprobe -show_packets` reports for each fixture:
# stream index, pts (Matroska ticks, 1 ms), keyframe flag and size per
# packet, in file order. Requires ffmpeg and ffprobe.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
fix="$root/tests/fixtures/media"
vec="$root/tests/vectors/mkv"
mkdir -p "$fix" "$vec"

common=(-hide_banner -loglevel error -y
  -f lavfi -i "testsrc2=size=160x120:rate=30"
  -f lavfi -i "sine=frequency=440:sample_rate=48000"
  -t 1
  -map 0:v -c:v libx264 -preset veryfast -tune zerolatency -bf 0 -g 15
  -pix_fmt yuv420p -b:v 100k
  -map 1:a -c:a:0 alac -ar:a:0 44100 -ac:a:0 2 -frame_size:a:0 4096
  -map 1:a -c:a:1 libopus -ar:a:1 48000 -ac:a:1 2 -b:a:1 32k
  -frame_duration:a:1 10 -application:a:1 lowdelay)

# What the pipeline produces: live mode, unknown-size Segment.
ffmpeg "${common[@]}" -f matroska -live 1 -cluster_time_limit 0 \
  -flush_packets 1 pipe:1 >"$fix/live.mkv"
# A regular file: SeekHead, Cues, CRC-32 elements, BlockGroups.
ffmpeg "${common[@]}" -f matroska "$fix/file.mkv"

for name in live file; do
  {
    echo "# Generated by scripts/gen-mkv-fixtures.sh from ffmpeg $(ffmpeg -version | head -1 | cut -d' ' -f3)."
    echo "# packets: 'stream pts flags size' per packet, ';'-separated, from"
    echo "# ffprobe -show_packets on tests/fixtures/media/$name.mkv."
    echo
    echo "name = $name"
    ffprobe -v error -show_entries stream=index,codec_name -of csv=p=0 "$fix/$name.mkv" |
      awk -F, '{ printf "stream%s = %s\n", $1, $2 }'
    echo "packets ="
    ffprobe -v error -show_entries packet=stream_index,pts,flags,size \
      -of csv=p=0 "$fix/$name.mkv" |
      awk -F, '{ printf "  %s %s %s %s;\n", $1, $2, substr($4, 1, 1), $3 }'
  } >"$vec/$name.txt"
done
ls -l "$fix"
