#!/usr/bin/env python3
"""Generates tests/vectors/airplay/{secure,pairing}.txt with the Python
`cryptography` package (OpenSSL), independent of ring and of our Rust code.

- secure.txt: control-channel keys (HKDF-SHA512, Control-Salt) and the
  framed ciphertext (u16le len | ChaCha20-Poly1305 | tag, AAD = len, LE
  counter nonce) for a few writes.
- pairing.txt: pair-setup M5/M6 and pair-verify M2/M3 encrypted payloads
  for fixed keys (Ed25519 signatures are deterministic).

Message layouts follow the HAP specification and pyatv (MIT)
`pyatv/auth/hap_srp.py`, `pyatv/protocols/airplay/server_auth.py`.

Usage: uv run --with cryptography scripts/vectors/airplay.py
"""
import os

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "vectors", "airplay")


def hkdf(salt, info, ikm, n=32):
    return HKDF(algorithm=hashes.SHA512(), length=n, salt=salt, info=info).derive(ikm)


def raw_pub(k):
    return k.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)


def tlv(items):
    out = b""
    for t, v in items:
        if not v:
            out += bytes([t, 0])
        for i in range(0, len(v), 255):
            c = v[i : i + 255]
            out += bytes([t, len(c)]) + c
    return out


def label_nonce(label):
    return b"\x00" * (12 - len(label)) + label


def counter_nonce(n):
    return b"\x00" * 4 + n.to_bytes(8, "little")


def frames(key, chunks, counter=0):
    c = ChaCha20Poly1305(key)
    out = b""
    for data in chunks:
        for i in range(0, max(len(data), 1), 1024):
            part = data[i : i + 1024]
            if not part:
                break
            ln = len(part).to_bytes(2, "little")
            out += ln + c.encrypt(counter_nonce(counter), part, ln)
            counter += 1
    return out


def block(lines):
    return "\n".join(f"{k} = {v}" for k, v in lines) + "\n"


def secure():
    blocks = []
    cases = [
        ("short", bytes(range(32)), [b"GET /info RTSP/1.0\r\nCSeq: 1\r\n\r\n"]),
        ("two writes", bytes([0xAB]) * 64, [b"hello", b"world!"]),
        ("multi frame", b"transient-K" * 5, [bytes((i * 7) & 0xFF for i in range(2100))]),
    ]
    for name, shared, writes in cases:
        wk = hkdf(b"Control-Salt", b"Control-Write-Encryption-Key", shared)
        rk = hkdf(b"Control-Salt", b"Control-Read-Encryption-Key", shared)
        lines = [("name", name), ("shared", shared.hex()), ("write_key", wk.hex()), ("read_key", rk.hex())]
        for i, w in enumerate(writes):
            lines.append((f"pt{i}", w.hex()))
        lines.append(("wire", frames(wk, writes).hex()))
        blocks.append(block(lines))
    with open(os.path.join(OUT, "secure.txt"), "w") as f:
        f.write("# Generated by scripts/vectors/airplay.py (Python cryptography). Do not edit.\n\n")
        f.write("\n".join(blocks))


def pairing():
    ctrl_seed = bytes(range(1, 33))
    acc_seed = bytes(range(101, 133))
    ctrl = Ed25519PrivateKey.from_private_bytes(ctrl_seed)
    acc = Ed25519PrivateKey.from_private_bytes(acc_seed)
    ctrl_id = b"9F3C2B6E-1D4A-4C8B-9E7F-0A1B2C3D4E5F"
    acc_id = b"AA:BB:CC:00:00:0A"

    # Pair-setup M5/M6 for a fixed SRP session key K.
    K = bytes((i * 13 + 5) & 0xFF for i in range(64))
    enc_key = hkdf(b"Pair-Setup-Encrypt-Salt", b"Pair-Setup-Encrypt-Info", K)
    ios_x = hkdf(b"Pair-Setup-Controller-Sign-Salt", b"Pair-Setup-Controller-Sign-Info", K)
    acc_x = hkdf(b"Pair-Setup-Accessory-Sign-Salt", b"Pair-Setup-Accessory-Sign-Info", K)
    m5_sub = tlv([
        (0x01, ctrl_id),
        (0x03, raw_pub(ctrl)),
        (0x0A, ctrl.sign(ios_x + ctrl_id + raw_pub(ctrl))),
    ])
    m5_enc = ChaCha20Poly1305(enc_key).encrypt(label_nonce(b"PS-Msg05"), m5_sub, None)
    m6_sub = tlv([
        (0x01, acc_id),
        (0x03, raw_pub(acc)),
        (0x0A, acc.sign(acc_x + acc_id + raw_pub(acc))),
    ])
    m6_enc = ChaCha20Poly1305(enc_key).encrypt(label_nonce(b"PS-Msg06"), m6_sub, None)
    setup = block([
        ("name", "pair-setup M5/M6"),
        ("controller_seed", ctrl_seed.hex()),
        ("controller_id", ctrl_id.hex()),
        ("accessory_seed", acc_seed.hex()),
        ("accessory_id", acc_id.hex()),
        ("K", K.hex()),
        ("m5_encrypted", m5_enc.hex()),
        ("m6_encrypted", m6_enc.hex()),
        ("transient_write_key", hkdf(b"Control-Salt", b"Control-Write-Encryption-Key", K).hex()),
        ("transient_read_key", hkdf(b"Control-Salt", b"Control-Read-Encryption-Key", K).hex()),
    ])

    # Pair-verify M2/M3 for fixed ephemeral X25519 keys.
    ce = X25519PrivateKey.from_private_bytes(bytes(range(201, 233)))
    ae = X25519PrivateKey.from_private_bytes(bytes(range(51, 83)))
    shared = ce.exchange(ae.public_key())
    vkey = hkdf(b"Pair-Verify-Encrypt-Salt", b"Pair-Verify-Encrypt-Info", shared)
    ce_pub, ae_pub = raw_pub(ce), raw_pub(ae)
    m2_sub = tlv([(0x01, acc_id), (0x0A, acc.sign(ae_pub + acc_id + ce_pub))])
    m2_enc = ChaCha20Poly1305(vkey).encrypt(label_nonce(b"PV-Msg02"), m2_sub, None)
    m3_sub = tlv([(0x01, ctrl_id), (0x0A, ctrl.sign(ce_pub + ctrl_id + ae_pub))])
    m3_enc = ChaCha20Poly1305(vkey).encrypt(label_nonce(b"PV-Msg03"), m3_sub, None)
    verify = block([
        ("name", "pair-verify M2/M3"),
        ("controller_seed", ctrl_seed.hex()),
        ("controller_id", ctrl_id.hex()),
        ("accessory_seed", acc_seed.hex()),
        ("accessory_id", acc_id.hex()),
        ("controller_ephemeral", ce_pub.hex()),
        ("accessory_ephemeral", ae_pub.hex()),
        ("shared", shared.hex()),
        ("m2_encrypted", m2_enc.hex()),
        ("m3_encrypted", m3_enc.hex()),
        ("control_write_key", hkdf(b"Control-Salt", b"Control-Write-Encryption-Key", shared).hex()),
        ("control_read_key", hkdf(b"Control-Salt", b"Control-Read-Encryption-Key", shared).hex()),
    ])
    with open(os.path.join(OUT, "pairing.txt"), "w") as f:
        f.write("# Generated by scripts/vectors/airplay.py (Python cryptography). Do not edit.\n\n")
        f.write(setup + "\n" + verify)


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    secure()
    pairing()
