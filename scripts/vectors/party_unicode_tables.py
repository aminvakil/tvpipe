#!/usr/bin/env python3
"""Writes crates/tvpipe-party/src/names/tables.rs: the Unicode data the
party host needs to clean player names like @tvpipe/party does
(docs/multiscreen-design.md §1.6), from Python's unicodedata.

- canonical decompositions (full NFD) of every character,
- compatibility decompositions (full NFKD) of U+00A0..U+33FF and
  U+FB00..U+FFEF (Latin, Greek, Cyrillic, punctuation, letterlike,
  fullwidth forms, ligatures; not CJK compatibility or math letters),
- canonical compositions (primary composites, exclusions honoured),
- canonical combining classes and the General_Category M ranges.

Hangul syllables are algorithmic and not in the tables.

    python3 scripts/vectors/party_unicode_tables.py
"""

import os
import unicodedata as u

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
OUT = os.path.join(ROOT, "crates", "tvpipe-party", "src", "names", "tables.rs")


def hangul(c):
    return 0xAC00 <= c <= 0xD7A3


def compat_range(c):
    return 0xA0 <= c < 0x3400 or 0xFB00 <= c < 0xFFF0


def surrogate(c):
    return 0xD800 <= c <= 0xDFFF


def esc(s):
    return "".join(f"\\u{{{ord(ch):x}}}" for ch in s)


decomp = []  # (code, nfd, nfkd); "" when the same as the other or none
for c in range(0x110000):
    if surrogate(c) or hangul(c):
        continue
    ch = chr(c)
    nfd = u.normalize("NFD", ch)
    nfkd = u.normalize("NFKD", ch) if compat_range(c) else nfd
    if nfd == ch and nfkd == ch:
        continue
    decomp.append((c, "" if nfd == ch else nfd, nfkd))

compose = []
for c in range(0x110000):
    if surrogate(c) or hangul(c):
        continue
    d = u.decomposition(chr(c))
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) != 2:
        continue
    a, b = chr(parts[0]), chr(parts[1])
    if u.normalize("NFC", a + b) == chr(c):
        compose.append((parts[0], parts[1], c))
compose.sort()


def ranges(pred):
    out = []
    for c in range(0x110000):
        if surrogate(c):
            continue
        v = pred(c)
        if v is None:
            continue
        if out and out[-1][1] == c - 1 and out[-1][2] == v:
            out[-1][1] = c
        else:
            out.append([c, c, v])
    return out


ccc = ranges(lambda c: u.combining(chr(c)) or None)
marks = ranges(lambda c: True if u.category(chr(c)).startswith("M") else None)

with open(OUT, "w") as f:
    f.write(f"// Generated by scripts/vectors/party_unicode_tables.py from Unicode {u.unidata_version}. Do not edit.\n\n")
    f.write("/// `(char, full NFD or \"\", full NFKD)`, sorted.\n")
    f.write(f"pub(super) static DECOMPOSITIONS: [(char, &str, &str); {len(decomp)}] = [\n")
    for c, nfd, nfkd in decomp:
        f.write(f"    ('\\u{{{c:x}}}', \"{esc(nfd)}\", \"{esc(nfkd)}\"),\n")
    f.write("];\n\n")
    f.write("/// `(first, second, composite)`, sorted.\n")
    f.write(f"pub(super) static COMPOSITIONS: [(char, char, char); {len(compose)}] = [\n")
    for a, b, c in compose:
        f.write(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}', '\\u{{{c:x}}}'),\n")
    f.write("];\n\n")
    f.write("/// Canonical combining classes: `(first, last, class)`, sorted.\n")
    f.write(f"pub(super) static COMBINING: [(u32, u32, u8); {len(ccc)}] = [\n")
    for a, b, k in ccc:
        f.write(f"    (0x{a:x}, 0x{b:x}, {k}),\n")
    f.write("];\n\n")
    f.write("/// General_Category M (marks): `(first, last)`, sorted.\n")
    f.write(f"pub(super) static MARKS: [(u32, u32); {len(marks)}] = [\n")
    for a, b, _ in marks:
        f.write(f"    (0x{a:x}, 0x{b:x}),\n")
    f.write("];\n")
print(f"wrote {OUT}: {len(decomp)} decompositions, {len(compose)} compositions, {len(ccc)} class ranges, {len(marks)} mark ranges")
