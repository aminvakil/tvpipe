#!/usr/bin/env python3
"""Generates tests/vectors/crypto/bigint.txt with Python's built-in integers
(`+`, `-`, `*`, `%`, `pow(a, e, m)`), an implementation independent of
src/crypto/bigint.rs. Deterministic (fixed seed).

Usage: python3 scripts/vectors/bigint.py   (from the repository root)
"""
import os
import random

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "vectors", "crypto", "bigint.txt")
MAX = 1 << 4096
rng = random.Random(5054)


def h(v):
    s = format(v, "x")
    return s if len(s) % 2 == 0 else "0" + s


def rnd(bits):
    return rng.getrandbits(bits) if bits else 0


# RFC 5054 3072-bit group prime (also used by HAP SRP).
N3072 = int(
    "FFFFFFFFFFFFFFFFC90FDAA22168C234C4C6628B80DC1CD129024E088A67CC74"
    "020BBEA63B139B22514A08798E3404DDEF9519B3CD3A431B302B0A6DF25F1437"
    "4FE1356D6D51C245E485B576625E7EC6F44C42E9A637ED6B0BFF5CB6F406B7ED"
    "EE386BFB5A899FA5AE9F24117C4B1FE649286651ECE45B3DC2007CB8A163BF05"
    "98DA48361C55D39A69163FA8FD24CF5F83655D23DCA3AD961C62F356208552BB"
    "9ED529077096966D670C354E4ABC9804F1746C08CA18217C32905E462E36CE3B"
    "E39E772C180E86039B2783A2EC07A28FB5C55DF06F4C52C9DE2BCBF695581718"
    "3995497CEA956AE515D2261898FA051015728E5A8AAAC42DAD33170D04507A33"
    "A85521ABDF1CBA64ECFB850458DBEF0A8AEA71575D060C7DB3970F85A6E1E4C7"
    "ABF5AE8CDB0933D71E8C94E04A25619DCEE3D2261AD2EE6BF12FFA06D98A0864"
    "D87602733EC86A64521F2B18177B200CBBE117577A615D6C770988C0BAD946E2"
    "08E24FA074E5AB3143DB5BFCE0FD108E4B82D120A93AD2CAFFFFFFFFFFFFFFFF",
    16,
)

blocks = []


def add(op, name, **kv):
    blocks.append([("name", name), ("op", op)] + [(k, h(v)) for k, v in kv.items()])


SIZES = [1, 63, 64, 65, 127, 128, 512, 1024, 2048, 3072, 4095, 4096]

for bits in SIZES:
    for _ in range(1):
        a, b = rnd(bits), rnd(rng.choice(SIZES))
        if a + b < MAX:
            add("add", f"add {bits}", a=a, b=b, r=a + b)
        hi, lo = max(a, b), min(a, b)
        add("sub", f"sub {bits}", a=hi, b=lo, r=hi - lo)
        x, y = rnd(bits // 2 + 1), rnd(4096 - bits // 2 - 2)
        add("mul", f"mul {bits}", a=x, b=y, r=x * y)

# Carry and borrow propagation across every limb.
add("add", "add carry chain", a=MAX - 1 - (1 << 4000), b=1, r=MAX - (1 << 4000))
add("add", "add carry chain 2", a=(1 << 4000) - 1, b=1, r=1 << 4000)
add("sub", "sub borrow chain", a=1 << 4000, b=1, r=(1 << 4000) - 1)
add("sub", "sub to zero", a=N3072, b=N3072, r=0)
add("mul", "mul by zero", a=N3072, b=0, r=0)
add("mul", "mul all-ones halves", a=(1 << 2048) - 1, b=(1 << 2048) - 1, r=((1 << 2048) - 1) ** 2)

for mbits in [1, 2, 64, 65, 521, 2048, 3072, 4096]:
    for even in (False, True):
        m = rnd(mbits) | (1 << (mbits - 1))
        m = (m & ~1) if even else (m | 1)
        if m == 0:
            continue
        tag = f"{mbits}-bit {'even' if even else 'odd'} m"
        a = rnd(min(4096, 2 * mbits + 7))
        add("rem", f"rem {tag}", a=a, m=m, r=a % m)
        x, y = rnd(mbits), rnd(rng.choice([1, 64, mbits, 4096]))
        add("modadd", f"modadd {tag}", a=x, b=y, m=m, r=(x + y) % m)
        add("modsub", f"modsub {tag}", a=x, b=y, m=m, r=(x - y) % m)
        add("modsub", f"modsub reversed {tag}", a=y, b=x, m=m, r=(y - x) % m)
        x, y = rnd(min(4096, mbits + 3)), rnd(4096 if mbits == 3072 else mbits)
        add("modmul", f"modmul {tag}", a=x, b=y, m=m, r=(x * y) % m)
        # Even moduli use the slow path: keep their exponents short.
        for ebits in ([0, 1, 17] if even else [0, 1, 64, mbits] + ([4096] if mbits == 3072 else [])):
            base, e = rnd(min(4096, mbits + 1)), rnd(ebits)
            add("modpow", f"modpow {tag} e{ebits}", a=base, e=e, m=m, r=pow(base, e, m))

# Edge cases.
add("modpow", "modpow m=1", a=5, e=3, m=1, r=0)
add("modpow", "modpow 0^0", a=0, e=0, m=7, r=1)
add("modpow", "modpow 0^5", a=0, e=5, m=7, r=0)
add("modpow", "modpow base=m", a=N3072, e=5, m=N3072, r=0)
add("modpow", "modpow base=m-1 squared", a=N3072 - 1, e=2, m=N3072, r=1)
add("modpow", "modpow Fermat N3072", a=2, e=N3072 - 1, m=N3072, r=1)
add("modpow", "modpow g=5 N3072 512-bit e", a=5, e=(e := rnd(512)), m=N3072, r=pow(5, e, N3072))
add("modpow", "modpow max m", a=(MAX - 3), e=(e := rnd(4096)), m=MAX - 1, r=pow(MAX - 3, e, MAX - 1))
add("rem", "rem a<m", a=5, m=N3072, r=5)
add("rem", "rem a=m", a=N3072, m=N3072, r=0)
add("rem", "rem max by 1", a=MAX - 1, m=1, r=0)

with open(OUT, "w") as f:
    f.write("# Generated by scripts/vectors/bigint.py (Python int arithmetic, seed 5054).\n")
    f.write("# op = add|sub|mul|rem|modadd|modsub|modmul|modpow; all values big-endian hex.\n")
    for blk in blocks:
        f.write("\n")
        for k, v in blk:
            if k not in ("name", "op") and len(v) > 64:
                v = "\n    ".join(v[i:i + 64] for i in range(0, len(v), 64))
            f.write(f"{k} = {v}\n")
print(len(blocks), "blocks")
