#!/usr/bin/env python3
"""Generates tests/vectors/crypto/{sha,hmac,hkdf}.txt with Python's stdlib.

hashlib/hmac are an implementation independent of ring. HKDF is the
two-step construction of RFC 5869 §2, written out here; the script checks
itself against RFC 5869 A.1 before writing anything.

Usage: python3 scripts/vectors/hashes.py   (from the repository root)
"""
import hashlib
import hmac
import os

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "tests", "vectors", "crypto")


def hkdf(alg, salt, ikm, info, length):
    hlen = hashlib.new(alg).digest_size
    if not salt:
        salt = b"\0" * hlen
    prk = hmac.new(salt, ikm, alg).digest()
    okm, t, i = b"", b"", 1
    while len(okm) < length:
        t = hmac.new(prk, t + info + bytes([i]), alg).digest()
        okm += t
        i += 1
    return okm[:length]


# RFC 5869 A.1 self-check.
assert hkdf("sha256", bytes(range(13)), b"\x0b" * 22, bytes(range(0xF0, 0xFA)), 42).hex() == (
    "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865"
)

# Messages: empty, FIPS 180 "abc", the two-block FIPS 180 message, a long one.
MSGS = [
    ("empty", b""),
    ("abc", b"abc"),
    ("fips180 448-bit", b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
    ("1000 bytes", bytes((i * 7 + 3) & 0xFF for i in range(1000))),
]


def hexs(b):
    return b.hex() if b else ""


def write(name, header, blocks):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(header)
        for blk in blocks:
            f.write("\n")
            for k, v in blk:
                f.write(f"{k} = {v}\n")


hdr = "# Generated by scripts/vectors/hashes.py (Python hashlib/hmac).\n"

sha = []
for label, m in MSGS:
    for alg in ("sha1", "sha256", "sha512"):
        sha.append([("name", f"{alg} {label}"), ("alg", alg), ("msg", hexs(m)),
                    ("md", hashlib.new(alg, m).hexdigest())])
write("sha.txt", hdr, sha)

KEYS = [
    ("RFC 4231 case 2 key", b"Jefe", b"what do ya want for nothing?"),
    ("20-byte key", b"\x0b" * 20, b"Hi There"),
    ("131-byte key (longer than block)", b"\xaa" * 131,
     b"Test Using Larger Than Block-Size Key - Hash Key First"),
    ("empty key", b"", b"abc"),
]
mac = []
for label, k, m in KEYS:
    for alg in ("sha1", "sha256", "sha512"):
        mac.append([("name", f"hmac-{alg} {label}"), ("alg", alg), ("key", hexs(k)),
                    ("msg", hexs(m)), ("mac", hmac.new(k, m, alg).hexdigest())])
write("hmac.txt", hdr, mac)

CASES = [
    ("RFC 5869 A.1 inputs", bytes(range(13)), b"\x0b" * 22, bytes(range(0xF0, 0xFA)), 42),
    ("empty salt and info", b"", b"\x0b" * 22, b"", 42),
    ("HAP pair-setup style", b"Pair-Setup-Encrypt-Salt", bytes(range(64)),
     b"Pair-Setup-Encrypt-Info", 32),
    ("long output", b"salt", b"ikm", b"info", 200),
]
kdf = []
for label, s, ikm, info, n in CASES:
    for alg in ("sha256", "sha512"):
        kdf.append([("name", f"hkdf-{alg} {label}"), ("alg", alg), ("salt", hexs(s)),
                    ("ikm", hexs(ikm)), ("info", hexs(info)), ("len", str(n)),
                    ("okm", hkdf(alg, s, ikm, info, n).hex())])
write("hkdf.txt", hdr + "# HKDF per RFC 5869; self-checked against RFC 5869 A.1.\n", kdf)
