#!/usr/bin/env bash
# Regenerates tests/vectors/h264/sps.txt from ffmpeg-encoded streams.
#
# Each block holds the first SPS and PPS NAL (Annex B start codes stripped,
# emulation prevention bytes kept) and the values ffprobe reports for the
# stream. Requires ffmpeg, ffprobe and python3.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/tests/vectors/h264/sps.txt"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

enc() {
  # enc NAME SIZE RATE ENCODER_ARGS...
  local name="$1" size="$2" rate="$3"
  shift 3
  echo "$rate" >"$tmp/$name.rate"
  ffmpeg -hide_banner -loglevel error -y \
    -f lavfi -i "testsrc2=size=$size:rate=$rate" -frames:v 3 "$@" \
    "$tmp/$name.h264"
}

enc baseline 320x240 30 -c:v libx264 -profile:v baseline -pix_fmt yuv420p
enc high1080 1920x1080 25 -c:v libx264 -profile:v high -pix_fmt yuv420p
enc main642 642x362 30000/1001 -c:v libx264 -profile:v main -pix_fmt yuv420p
enc high10 1280x720 60 -c:v libx264 -profile:v high10 -pix_fmt yuv420p10le
enc high444 352x288 50 -c:v libx264 -profile:v high444 -pix_fmt yuv444p
enc high422 176x144 15 -c:v libx264 -profile:v high422 -pix_fmt yuv422p
enc interlaced 720x576 25 -c:v libx264 -x264-params interlaced=1 -pix_fmt yuv420p
enc scaling 1280x720 24 -c:v libx264 -x264-params cqm=jvt -profile:v high -pix_fmt yuv420p
if ffmpeg -hide_banner -encoders 2>/dev/null | grep -q h264_videotoolbox; then
  enc videotoolbox 1920x1080 60 -c:v h264_videotoolbox -realtime 1
fi

{
  echo "# Generated by scripts/gen-h264-vectors.sh from ffmpeg $(ffmpeg -version | head -1 | cut -d' ' -f3)."
  echo "# sps/pps: NAL units without start code. avcc: ffmpeg's mp4 avcC box body."
  echo "# width/height/ffprobe_*: from ffprobe."
  echo "# encoder_fps: the rate given to the encoder. Syntax element values"
  echo "# (chroma_format_idc ... time_scale) come from ffmpeg -bsf:v trace_headers;"
  echo "# '-' means the element is absent (default applies)."
  for f in "$tmp"/*.h264; do
    name="$(basename "$f" .h264)"
    probe="$(ffprobe -v error -select_streams v:0 \
      -show_entries stream=profile,level,width,height,field_order \
      -of default=noprint_wrappers=1 "$f")"
    ffmpeg -hide_banner -i "$f" -c copy -bsf:v trace_headers -f null - \
      2>"$tmp/$name.trace" >/dev/null
    ffmpeg -hide_banner -loglevel error -y -i "$f" -c copy -f mp4 "$tmp/$name.mp4"
    python3 - "$f" "$name" "$(cat "$tmp/$name.rate")" "$tmp/$name.trace" <<PY
import sys
data = open(sys.argv[1], "rb").read()
probe = dict(l.split("=", 1) for l in """$probe""".splitlines())
nals, i = [], 0
starts = []
while True:
    j = data.find(b"\x00\x00\x01", i)
    if j < 0:
        break
    starts.append(j + 3)
    i = j + 3
for k, s in enumerate(starts):
    e = starts[k + 1] - 3 if k + 1 < len(starts) else len(data)
    nal = data[s:e]
    while k + 1 < len(starts) and nal.endswith(b"\x00"):
        nal = nal[:-1]
    nals.append(nal)
sps = next(n for n in nals if n[0] & 0x1F == 7)
pps = next(n for n in nals if n[0] & 0x1F == 8)
mp4 = open(sys.argv[1][:-5] + ".mp4", "rb").read()
at = mp4.find(b"avcC")
avcc = mp4[at + 4:at - 4 + int.from_bytes(mp4[at - 4:at], "big")]
print()
print("name =", sys.argv[2])
print("sps =", sps.hex())
print("pps =", pps.hex())
print("avcc =", avcc.hex())
print("profile_idc =", sps[1])
print("level_idc =", sps[3])
print("encoder_fps =", sys.argv[3])
# First SPS fields from ffmpeg's trace_headers bitstream filter.
trace, in_sps = {}, False
for line in open(sys.argv[4]):
    if "Sequence Parameter Set" in line:
        if trace:
            break
        in_sps = True
        continue
    if in_sps and ("Parameter Set" in line or "Slice" in line or "Supplemental" in line):
        break
    if in_sps and " = " in line:
        parts = line.split("]", 1)[1].split()
        trace.setdefault(parts[1], parts[-1])
for key in ("chroma_format_idc", "bit_depth_luma_minus8", "frame_mbs_only_flag",
            "frame_cropping_flag", "frame_crop_left_offset", "frame_crop_right_offset",
            "frame_crop_top_offset", "frame_crop_bottom_offset", "timing_info_present_flag",
            "num_units_in_tick", "time_scale"):
    print(key, "=", trace.get(key, "-"))
print("width =", probe["width"])
print("height =", probe["height"])
print("ffprobe_profile =", probe["profile"])
print("ffprobe_level =", probe["level"])
print("interlaced =", "0" if probe.get("field_order", "progressive") in ("progressive", "unknown") else "1")
print("nal_types =", " ".join(str(n[0] & 0x1F) for n in nals))
PY
  done
} >"$out"
echo "wrote $out"
