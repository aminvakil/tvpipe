#!/usr/bin/env bash
# Regenerates crates/tvpipe/tests/fixtures/media/*.{mp4,mov} and crates/tvpipe/tests/vectors/mp4/*.txt.
#
# The vectors hold what ffprobe reports for each fixture: per stream the
# codec, time base and parameters, and per packet (in file order) stream
# index, pts, dts, duration, keyframe flag and size. Requires ffmpeg and
# ffprobe (with libx264, libx265, libopus).
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
fix="$root/crates/tvpipe/tests/fixtures/media"
vec="$root/crates/tvpipe/tests/vectors/mp4"
mkdir -p "$fix" "$vec"

ff=(ffmpeg -hide_banner -loglevel error -y)
src=(-f lavfi -i "testsrc2=size=160x120:rate=30"
  -f lavfi -i "sine=frequency=440:sample_rate=48000" -t 1)
x264=(-c:v libx264 -preset veryfast -pix_fmt yuv420p -b:v 100k -g 15)

# No B-frames, AAC-LC, moov after mdat (ffmpeg's default).
"${ff[@]}" "${src[@]}" "${x264[@]}" -bf 0 -tune zerolatency \
  -c:a aac -b:a 64k -ac 2 "$fix/bf0.mp4"
# B-frames (ctts, edit list), moov first.
"${ff[@]}" "${src[@]}" "${x264[@]}" -bf 2 \
  -c:a aac -b:a 64k -ac 2 -movflags +faststart "$fix/bframes.mp4"
# Fragmented MP4 with Opus.
"${ff[@]}" "${src[@]}" "${x264[@]}" -bf 0 -tune zerolatency \
  -c:a libopus -b:a 32k -ac 2 \
  -movflags frag_keyframe+empty_moov+default_base_moof "$fix/frag.mp4"
# QuickTime with ALAC at 44.1 kHz.
"${ff[@]}" "${src[@]}" "${x264[@]}" -bf 0 -tune zerolatency \
  -c:a alac -ar 44100 -ac 2 "$fix/alac.mov"
# QuickTime with 16-bit PCM ('sowt').
"${ff[@]}" "${src[@]}" "${x264[@]}" -bf 0 -tune zerolatency \
  -c:a pcm_s16le -ac 2 "$fix/pcm.mov"
# HEVC ('hvc1'), video only, half a second.
"${ff[@]}" -f lavfi -i "testsrc2=size=160x120:rate=30" -t 0.5 \
  -c:v libx265 -preset ultrafast -x265-params log-level=error:bframes=0 \
  -tag:v hvc1 -pix_fmt yuv420p "$fix/hevc.mp4"

for f in bf0.mp4 bframes.mp4 frag.mp4 alac.mov pcm.mov hevc.mp4; do
  name="${f%.*}"
  {
    echo "# Generated by scripts/gen-mp4-fixtures.sh from ffmpeg $(ffmpeg -version | head -1 | cut -d' ' -f3)."
    echo "# streams: 'index,codec,width,height,time_base' (video) or
#   'index,codec,sample_rate,channels,time_base' (audio) per stream."
    echo "# packets: 'stream pts dts duration flags size' per packet, ';'-separated,"
    echo "# in file order, from ffprobe -show_packets on crates/tvpipe/tests/fixtures/media/$f."
    echo
    echo "name = $name"
    echo "file = $f"
    echo "streams ="
    ffprobe -v error -show_entries \
      stream=index,codec_name,time_base,width,height,sample_rate,channels \
      -of csv=p=0 "$fix/$f" |
      awk -F, '{ printf "  %s;\n", $0 }'
    echo "packets ="
    ffprobe -v error -show_entries packet=stream_index,pts,dts,duration,flags,size \
      -of csv=p=0 "$fix/$f" |
      awk -F, '{ printf "  %s %s %s %s %s %s;\n", $1, $2, $3, $4, substr($6, 1, 1), $5 }'
  } >"$vec/$name.txt"
done
ls -l "$fix"
