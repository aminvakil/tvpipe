#!/usr/bin/env bash
# Regenerates tests/vectors/h264/reorder.txt: SPS NAL units with and
# without VUI bitstream_restriction (and with HRD parameters before it),
# and the values ffmpeg's trace_headers reports for them. Requires ffmpeg
# and python3.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/tests/vectors/h264/reorder.txt"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

enc() {
  # enc NAME ENCODER_ARGS...
  local name="$1"
  shift
  ffmpeg -hide_banner -loglevel error -y \
    -f lavfi -i "testsrc2=size=320x240:rate=30" -frames:v 5 "$@" "$tmp/$name.h264"
}

enc bf0 -c:v libx264 -tune zerolatency -pix_fmt yuv420p
enc bf2 -c:v libx264 -bf 2 -b-pyramid none -pix_fmt yuv420p
enc bf3pyramid -c:v libx264 -bf 3 -b-pyramid normal -pix_fmt yuv420p
enc hrd -c:v libx264 -bf 1 -b:v 500k -maxrate 500k -bufsize 500k \
  -x264-params nal-hrd=cbr -pix_fmt yuv420p
enc baseline -c:v libx264 -profile:v baseline -pix_fmt yuv420p
if ffmpeg -hide_banner -encoders 2>/dev/null | grep -q h264_videotoolbox; then
  enc videotoolbox -c:v h264_videotoolbox -realtime 1
fi

{
  echo "# Generated by scripts/gen-h264-reorder-vectors.sh from ffmpeg $(ffmpeg -version | head -1 | cut -d' ' -f3)."
  echo "# sps: first SPS NAL (no start code). Other keys: from ffmpeg -bsf:v"
  echo "# trace_headers; '-' means the element is absent."
  for f in "$tmp"/*.h264; do
    name="$(basename "$f" .h264)"
    ffmpeg -hide_banner -i "$f" -c copy -bsf:v trace_headers -f null - \
      2>"$tmp/$name.trace" >/dev/null
    python3 - "$f" "$name" "$tmp/$name.trace" <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
starts, i = [], 0
while True:
    j = data.find(b"\x00\x00\x01", i)
    if j < 0:
        break
    starts.append(j + 3)
    i = j + 3
nals = []
for k, s in enumerate(starts):
    e = starts[k + 1] - 3 if k + 1 < len(starts) else len(data)
    nal = data[s:e]
    while k + 1 < len(starts) and nal.endswith(b"\x00"):
        nal = nal[:-1]
    nals.append(nal)
sps = next(n for n in nals if n[0] & 0x1F == 7)
trace, in_sps = {}, False
for line in open(sys.argv[3]):
    if "Sequence Parameter Set" in line:
        if trace:
            break
        in_sps = True
        continue
    if in_sps and ("Parameter Set" in line or "Slice" in line or "Supplemental" in line):
        break
    if in_sps and " = " in line:
        parts = line.split("]", 1)[1].split()
        trace.setdefault(parts[1], parts[-1])
print()
print("name =", sys.argv[2])
print("sps =", sps.hex())
for key in ("nal_hrd_parameters_present_flag", "vcl_hrd_parameters_present_flag",
            "bitstream_restriction_flag", "max_num_reorder_frames",
            "max_dec_frame_buffering"):
    print(key, "=", trace.get(key, "-"))
PY
  done
} >"$out"
echo "wrote $out"
